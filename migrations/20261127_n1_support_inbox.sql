BEGIN;

CREATE TABLE public.support_message (
    support_message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id uuid NOT NULL REFERENCES public."user" (user_id) ON DELETE CASCADE,
    subject varchar(120) NOT NULL CHECK (char_length(btrim(subject)) BETWEEN 1 AND 120),
    message text NOT NULL CHECK (char_length(btrim(message)) BETWEEN 1 AND 5000),
    status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX support_message_customer_created_idx
    ON public.support_message (customer_id, created_at DESC);
CREATE INDEX support_message_status_created_idx
    ON public.support_message (status, created_at DESC);

CREATE TABLE public.support_message_history (
    support_message_history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    support_message_id bigint NOT NULL REFERENCES public.support_message (support_message_id) ON DELETE CASCADE,
    actor_user_id uuid NOT NULL REFERENCES public."user" (user_id),
    event_type text NOT NULL CHECK (event_type IN ('submitted', 'status_changed')),
    previous_status text CHECK (previous_status IN ('open', 'resolved')),
    new_status text CHECK (new_status IN ('open', 'resolved')),
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((event_type = 'submitted' AND previous_status IS NULL AND new_status = 'open') OR
           (event_type = 'status_changed' AND previous_status IS NOT NULL AND new_status IS NOT NULL AND previous_status <> new_status))
);

CREATE INDEX support_message_history_message_created_idx
    ON public.support_message_history (support_message_id, created_at);

CREATE TABLE public.support_message_admin_notification (
    support_message_id bigint NOT NULL REFERENCES public.support_message (support_message_id) ON DELETE CASCADE,
    admin_user_id uuid NOT NULL REFERENCES public."user" (user_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (support_message_id, admin_user_id)
);

CREATE INDEX support_message_admin_notification_admin_created_idx
    ON public.support_message_admin_notification (admin_user_id, created_at DESC);

ALTER TABLE public.support_message ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_message_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_message_admin_notification ENABLE ROW LEVEL SECURITY;

CREATE POLICY support_message_customer_or_admin_select ON public.support_message
    FOR SELECT TO authenticated
    USING (
        customer_id = auth.uid() OR EXISTS (
            SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
            WHERE u.user_id = auth.uid() AND r.role_name = 'Admin'
        )
    );
CREATE POLICY support_message_customer_insert ON public.support_message
    FOR INSERT TO authenticated
    WITH CHECK (
        customer_id = auth.uid() AND EXISTS (
            SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
            WHERE u.user_id = auth.uid() AND r.role_name = 'Customer'
        )
    );
CREATE POLICY support_message_admin_update ON public.support_message
    FOR UPDATE TO authenticated
    USING (EXISTS (
        SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
        WHERE u.user_id = auth.uid() AND r.role_name = 'Admin'
    ))
    WITH CHECK (EXISTS (
        SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
        WHERE u.user_id = auth.uid() AND r.role_name = 'Admin'
    ));

CREATE POLICY support_message_history_customer_or_admin_select ON public.support_message_history
    FOR SELECT TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.support_message sm
            WHERE sm.support_message_id = support_message_history.support_message_id
              AND (sm.customer_id = auth.uid() OR EXISTS (
                  SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
                  WHERE u.user_id = auth.uid() AND r.role_name = 'Admin'
              ))
        )
    );
CREATE POLICY support_message_history_owner_submission ON public.support_message_history
    FOR INSERT TO authenticated
    WITH CHECK (
        actor_user_id = auth.uid() AND event_type = 'submitted' AND new_status = 'open' AND EXISTS (
            SELECT 1 FROM public.support_message sm
            WHERE sm.support_message_id = support_message_history.support_message_id
              AND sm.customer_id = auth.uid()
        )
    );
CREATE POLICY support_message_history_admin_status_change ON public.support_message_history
    FOR INSERT TO authenticated
    WITH CHECK (
        actor_user_id = auth.uid() AND event_type = 'status_changed' AND EXISTS (
            SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
            WHERE u.user_id = auth.uid() AND r.role_name = 'Admin'
        )
    );

CREATE POLICY support_message_admin_notification_recipient_select ON public.support_message_admin_notification
    FOR SELECT TO authenticated
    USING (
        admin_user_id = auth.uid() AND EXISTS (
            SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
            WHERE u.user_id = auth.uid() AND r.role_name = 'Admin'
        )
    );

CREATE FUNCTION public.create_support_message_admin_notifications()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF auth.uid() IS NULL OR auth.uid() <> NEW.customer_id OR NOT EXISTS (
        SELECT 1 FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
        WHERE u.user_id = auth.uid() AND r.role_name = 'Customer'
    ) OR NEW.status <> 'open' THEN
        RAISE EXCEPTION 'Unauthorized support notification creation' USING ERRCODE = '42501';
    END IF;

    INSERT INTO public.support_message_admin_notification (support_message_id, admin_user_id)
    SELECT NEW.support_message_id, u.user_id
    FROM public."user" u JOIN public.role r ON r.role_id = u.role_id
    WHERE r.role_name = 'Admin'
    ON CONFLICT (support_message_id, admin_user_id) DO NOTHING;

    RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION public.create_support_message_admin_notifications() FROM PUBLIC, anon, authenticated;

CREATE TRIGGER support_message_create_admin_notifications
    AFTER INSERT ON public.support_message
    FOR EACH ROW EXECUTE FUNCTION public.create_support_message_admin_notifications();

REVOKE ALL ON public.support_message, public.support_message_history, public.support_message_admin_notification FROM anon, authenticated;
GRANT SELECT, INSERT ON public.support_message TO authenticated;
GRANT UPDATE (status, updated_at) ON public.support_message TO authenticated;
GRANT SELECT, INSERT ON public.support_message_history TO authenticated;
GRANT SELECT ON public.support_message_admin_notification TO authenticated;

COMMIT;
