-- Media Support. Review and apply manually in Supabase; this file is not executed by the application.

create table if not exists public.media (
    media_id bigint generated by default as identity primary key,
    hotel_id bigint references public.hotel(hotel_id) on delete cascade,
    restaurant_id bigint references public.restaurant(restaurant_id) on delete cascade,
    room_id bigint references public.room(room_id) on delete cascade,
    table_id bigint references public.restaurant_table(table_id) on delete cascade,
    image_type varchar(20) not null,
    storage_bucket varchar(100) not null default 'reservation-media',
    storage_path text not null unique,
    file_size bigint not null,
    is_primary boolean not null default false,
    display_order integer not null default 0,
    created_at timestamptz not null default now(),
    constraint media_one_entity check (
        ((hotel_id is not null)::integer +
         (restaurant_id is not null)::integer +
         (room_id is not null)::integer +
         (table_id is not null)::integer) = 1
    ),
    constraint media_image_type check (image_type in ('JPG', 'PNG', 'WEBP')),
    constraint media_file_size_positive check (file_size > 0),
    constraint media_display_order_nonnegative check (display_order >= 0)
);

create unique index if not exists media_one_primary_hotel
    on public.media (hotel_id) where is_primary and hotel_id is not null;
create unique index if not exists media_one_primary_restaurant
    on public.media (restaurant_id) where is_primary and restaurant_id is not null;
create unique index if not exists media_one_primary_room
    on public.media (room_id) where is_primary and room_id is not null;
create unique index if not exists media_one_primary_table
    on public.media (table_id) where is_primary and table_id is not null;
create index if not exists media_hotel_order on public.media (hotel_id, display_order, media_id) where hotel_id is not null;
create index if not exists media_restaurant_order on public.media (restaurant_id, display_order, media_id) where restaurant_id is not null;
create index if not exists media_room_order on public.media (room_id, display_order, media_id) where room_id is not null;
create index if not exists media_table_order on public.media (table_id, display_order, media_id) where table_id is not null;

alter table public.media enable row level security;

create policy "authenticated users can view media"
    on public.media for select to authenticated using (true);

create policy "staff and admins can insert media"
    on public.media for insert to authenticated
    with check (exists (
        select 1 from public."user" u
        join public.role r on r.role_id = u.role_id
        where u.user_id = auth.uid() and r.role_name in ('Staff', 'Admin')
    ));

create policy "staff and admins can update media"
    on public.media for update to authenticated
    using (exists (
        select 1 from public."user" u
        join public.role r on r.role_id = u.role_id
        where u.user_id = auth.uid() and r.role_name in ('Staff', 'Admin')
    ))
    with check (exists (
